let a = 10;
let b = 11;

// Post-increment: Prints 10, then 'a' becomes 11
console.log(`a++: ${a++}`);

// Pre-increment: 'a' becomes 12, then prints 12
console.log(`++a: ${++a}`);

// Post-decrement: Prints 11, then 'b' becomes 10
console.log(`b--: ${b--}`);

// Pre-decrement: 'b' becomes 9, then prints 9
console.log(`--b: ${--b}`);
